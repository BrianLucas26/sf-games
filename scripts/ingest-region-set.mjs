#!/usr/bin/env node
// Generic region-set ingestion: fetches a GeoJSON FeatureCollection, computes
// each feature's centroid and adjacency (shared/overlapping borders) against
// every other feature, simplifies geometry for rendering (adjacency is
// computed from the *unsimplified* geometry first, so independent
// simplification per polygon can't introduce false negatives), and writes a
// SQL migration inserting it all under one map_region_sets slug.
//
// Reused as-is for any future spatial game by pointing at a different
// GeoJSON source and region-set slug (e.g. Territory Control's districts) --
// nothing here is SF-neighborhoods-specific.
//
// Usage:
//   node scripts/ingest-region-set.mjs \
//     --region-set-slug sf-neighborhoods \
//     --region-set-name "San Francisco Neighborhoods" \
//     --source "SF Planning Dept Analysis Neighborhoods (data.sfgov.org, dataset j2bu-swwd)" \
//     --geojson-url "https://data.sfgov.org/resource/j2bu-swwd.geojson?\$limit=200" \
//     --name-property nhood \
//     --output supabase/migrations/0009_seed_sf_neighborhoods.sql

import { writeFileSync } from 'node:fs'
import * as turf from '@turf/turf'

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`)
  return i === -1 ? fallback : process.argv[i + 1]
}

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

async function main() {
  const regionSetSlug = arg('region-set-slug')
  const regionSetName = arg('region-set-name')
  const source = arg('source')
  const geojsonUrl = arg('geojson-url')
  const nameProperty = arg('name-property')
  const simplifyTolerance = Number(arg('simplify-tolerance', '0.0001'))
  const output = arg('output')

  if (!regionSetSlug || !regionSetName || !source || !geojsonUrl || !nameProperty || !output) {
    console.error(
      'Missing required args: --region-set-slug --region-set-name --source --geojson-url --name-property --output',
    )
    process.exit(1)
  }

  console.log(`Fetching ${geojsonUrl} ...`)
  const res = await fetch(geojsonUrl)
  if (!res.ok) throw new Error(`Fetch failed: ${res.status} ${res.statusText}`)
  const geojson = await res.json()
  const features = geojson.features.filter((f) => f.geometry)
  console.log(`Got ${features.length} features.`)

  const rawSize = Buffer.byteLength(JSON.stringify(features.map((f) => f.geometry)))

  const regions = features.map((f) => {
    const name = f.properties[nameProperty]
    const centroid = turf.centroid(f).geometry.coordinates
    const simplified = turf.simplify(f, { tolerance: simplifyTolerance, highQuality: true })
    return {
      slug: slugify(name),
      name,
      geometry: simplified.geometry,
      rawFeature: f,
      centroidLng: centroid[0],
      centroidLat: centroid[1],
    }
  })

  const simplifiedSize = Buffer.byteLength(JSON.stringify(regions.map((r) => r.geometry)))
  console.log(
    `Geometry size: ${(rawSize / 1024).toFixed(0)}KB raw -> ${(simplifiedSize / 1024).toFixed(0)}KB simplified.`,
  )

  console.log('Computing adjacency (from unsimplified geometry)...')
  const adjacencyPairs = []
  for (let i = 0; i < regions.length; i++) {
    for (let j = i + 1; j < regions.length; j++) {
      if (turf.booleanIntersects(regions[i].rawFeature, regions[j].rawFeature)) {
        adjacencyPairs.push([regions[i].slug, regions[j].slug])
      }
    }
  }
  console.log(`Found ${adjacencyPairs.length} adjacent pairs.`)

  const lines = []
  lines.push('-- Generated by scripts/ingest-region-set.mjs -- do not hand-edit.')
  lines.push(`-- Source: ${source}`)
  lines.push('')
  lines.push(
    '-- Pre-launch: no real game has been played yet, so it is safe to clear all games',
  )
  lines.push(
    '-- (cascades to teams/players/turf_war_* instance tables) before replacing the',
  )
  lines.push('-- placeholder region set below.')
  lines.push('delete from games;')
  lines.push('')
  lines.push('delete from map_regions')
  lines.push(
    `where region_set_id = (select id from map_region_sets where slug = ${sqlString(regionSetSlug)});`,
  )
  lines.push('')
  lines.push('insert into map_region_sets (slug, name, source)')
  lines.push(
    `values (${sqlString(regionSetSlug)}, ${sqlString(regionSetName)}, ${sqlString(source)})`,
  )
  lines.push('on conflict (slug) do update set name = excluded.name, source = excluded.source;')
  lines.push('')

  lines.push('insert into map_regions (region_set_id, slug, name, geometry, centroid_lat, centroid_lng)')
  lines.push('select rs.id, v.slug, v.name, v.geometry::jsonb, v.centroid_lat, v.centroid_lng')
  lines.push('from map_region_sets rs,')
  lines.push('  (values')
  lines.push(
    regions
      .map(
        (r) =>
          `    (${sqlString(r.slug)}, ${sqlString(r.name)}, ${sqlString(JSON.stringify(r.geometry))}, ${r.centroidLat}, ${r.centroidLng})`,
      )
      .join(',\n'),
  )
  lines.push('  ) as v(slug, name, geometry, centroid_lat, centroid_lng)')
  lines.push(`where rs.slug = ${sqlString(regionSetSlug)};`)
  lines.push('')

  if (adjacencyPairs.length > 0) {
    lines.push('with pairs (region_slug, neighbor_slug) as (')
    lines.push('  values')
    const pairRows = []
    for (const [a, b] of adjacencyPairs) {
      pairRows.push(`    (${sqlString(a)}, ${sqlString(b)})`)
      pairRows.push(`    (${sqlString(b)}, ${sqlString(a)})`)
    }
    lines.push(pairRows.join(',\n'))
    lines.push(')')
    lines.push('insert into map_region_adjacency (region_id, neighbor_id)')
    lines.push('select r1.id, r2.id')
    lines.push('from pairs p')
    lines.push('join map_regions r1 on r1.slug = p.region_slug')
    lines.push('join map_regions r2 on r2.slug = p.neighbor_slug')
    lines.push(`join map_region_sets rs on rs.id = r1.region_set_id and rs.slug = ${sqlString(regionSetSlug)};`)
    lines.push('')
  }

  lines.push("insert into turf_war_challenges (region_id, prompt)")
  lines.push("select r.id, 'PLACEHOLDER: take a selfie somewhere in ' || r.name || '.'")
  lines.push('from map_regions r')
  lines.push('join map_region_sets rs on rs.id = r.region_set_id')
  lines.push(`where rs.slug = ${sqlString(regionSetSlug)}`)
  lines.push('on conflict (region_id) do nothing;')
  lines.push('')

  writeFileSync(output, lines.join('\n'))
  console.log(`Wrote ${output}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
